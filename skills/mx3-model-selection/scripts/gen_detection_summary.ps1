<#
.SYNOPSIS
  Regenerate references/detection-summary.md from references/tx8-freq-matrix.csv.

.DESCRIPTION
  Lists every detection-like model (task detect or obb, same name heuristic as freq_query.ps1)
  with status / fps / module power at 300 and 400 MHz and the frequency-rule result for
  TargetFps (default 30, safety 1.5, max 400 MHz). Read-only on the CSV; writes only the
  markdown output file. PowerShell 5.1 compatible.

.EXAMPLE
  powershell -NoProfile -File gen_detection_summary.ps1
.EXAMPLE
  powershell -NoProfile -File gen_detection_summary.ps1 -TargetFps 25 -Out C:\tmp\summary.md
#>
[CmdletBinding()]
param(
    [string]$Csv = '',
    [string]$Out = '',
    [double]$TargetFps = 30,
    [double]$Safety = 1.5,
    [switch]$Help
)
Set-StrictMode -Version 2.0
$ErrorActionPreference = 'Stop'
if ($Help) { Get-Help -Detailed $MyInvocation.MyCommand.Path; exit 0 }

$here = Split-Path -Parent $MyInvocation.MyCommand.Path
if ($Csv -eq '') { $Csv = Join-Path $here '..\references\tx8-freq-matrix.csv' }
if ($Out -eq '') { $Out = Join-Path $here '..\references\detection-summary.md' }

function Get-TaskOf([string]$name) {
    $n = $name.ToLowerInvariant()
    if ($n -match 'oriented_bounding_boxes|_obb') { return 'obb' }
    if ($n -match 'pose|kpts|keypoint|landmark') { return 'pose' }
    if ($n -match '_cls_|classif|malaria_detector') { return 'classify' }
    if ($n -match '_seg_|segment|deeplab|unet|bisenet|pspnet|lanenet|yolop') { return 'segment' }
    if ($n -match 'depth|midas|dpt_') { return 'depth' }
    if ($n -match '3d|pointpillars|centerpoint|text_detection') { return 'other' }
    if ($n -match 'yolo|ssd|rtmdet|nanodet|damo|efficientdet|centernet|detection|detector|detr|retinanet|fcos|mobiledet|yunet') { return 'detect' }
    return 'other'
}
function Get-InputOf([string]$name) {
    $m = [regex]::Match($name, '_(\d+)_(\d+)_(\d+)_(onnx|tflite|tensorflow|keras)$')
    if ($m.Success) { return ('{0}x{1}' -f $m.Groups[1].Value, $m.Groups[2].Value) }
    return '?'
}
function Get-Family([string]$name) {
    $n = $name.ToLowerInvariant()
    if ($n -match '^yolo26') { return 'YOLO26' }
    if ($n -match '^yolo11') { return 'YOLO11' }
    if ($n -match '^yolo_v10') { return 'YOLOv10' }
    if ($n -match '^yolo_v9') { return 'YOLOv9' }
    if ($n -match '^yolo_v8') { return 'YOLOv8' }
    if ($n -match '^yolo_v7') { return 'YOLOv7' }
    if ($n -match '^yolo_v6') { return 'YOLOv6' }
    if ($n -match '^yolo_v5') { return 'YOLOv5' }
    if ($n -match '^yolox') { return 'YOLOX' }
    if ($n -match '^yolo_nas') { return 'YOLO-NAS' }
    if ($n -match '^yolo|yolo_v[234]|mobilenet_yolo') { return 'YOLO (older)' }
    if ($n -match 'rtmdet') { return 'RTMDet' }
    if ($n -match 'nanodet') { return 'NanoDet' }
    if ($n -match 'damo') { return 'DAMO-YOLO' }
    if ($n -match 'efficientdet') { return 'EfficientDet' }
    if ($n -match 'centernet') { return 'CenterNet' }
    if ($n -match 'ssd') { return 'SSD' }
    return 'Other detectors'
}
function Cell($r) {
    if ($null -eq $r) { return 'n/a' }
    if ($r.status -ne 'PASS') { return 'NG' }
    return ('{0} / {1}' -f ([double]$r.fps).ToString('0.0', [Globalization.CultureInfo]::InvariantCulture), $r.power_mw)
}

$need = $TargetFps * $Safety
$rows = Get-Content -Path $Csv | Where-Object { $_ -notmatch '^\s*#' -and $_.Trim() -ne '' } | ConvertFrom-Csv
$items = @()
foreach ($g in ($rows | Group-Object model)) {
    $t = Get-TaskOf $g.Name
    if ($t -ne 'detect' -and $t -ne 'obb') { continue }
    $r300 = $g.Group | Where-Object { $_.freq_mhz -eq '300' } | Select-Object -First 1
    $r400 = $g.Group | Where-Object { $_.freq_mhz -eq '400' } | Select-Object -First 1
    $rule = 'not recommended'
    foreach ($r in @($r300, $r400)) {
        if ($null -ne $r -and $r.status -eq 'PASS' -and $r.fps -ne '' -and [double]$r.fps -ge $need) { $rule = "$($r.freq_mhz) MHz"; break }
    }
    $items += [pscustomobject]@{
        family = Get-Family $g.Name; model = $g.Name; task = $t; input = Get-InputOf $g.Name
        c300 = Cell $r300; c400 = Cell $r400; rule = $rule
    }
}

$families = @('YOLO26', 'YOLOv10', 'YOLO11', 'YOLOv9', 'YOLOv8', 'YOLOv7', 'YOLOv6', 'YOLOv5', 'YOLOX', 'YOLO-NAS',
    'YOLO (older)', 'RTMDet', 'NanoDet', 'DAMO-YOLO', 'EfficientDet', 'CenterNet', 'SSD', 'Other detectors')
$ok = @($items | Where-Object { $_.rule -ne 'not recommended' }).Count

$sb = New-Object System.Text.StringBuilder
[void]$sb.AppendLine('# Detection models in the MX3 frequency matrix (300 / 400 MHz)')
[void]$sb.AppendLine('')
[void]$sb.AppendLine('<!-- GENERATED by scripts/gen_detection_summary.ps1 from references/tx8-freq-matrix.csv. Do not edit by hand; re-run the script. -->')
[void]$sb.AppendLine('')
[void]$sb.AppendLine('Source: MemryX reference table (`model_inference_results_by_frequency.xlsx`), config 4x1 = **4 MX3 chips**.')
[void]$sb.AppendLine('**This is NOT TX8 data**: fps is accelerator throughput measured by MemryX on their host; TX8')
[void]$sb.AppendLine('(4x Cortex-A53) must re-verify end-to-end fps, latency and power (skill `mx3-runtime-integration`).')
[void]$sb.AppendLine('')
[void]$sb.AppendLine(('Cells: `fps / module power mW`; `NG` = failed or no record at that clock; `n/a` = row missing. ' +
        'Rule column = lowest PASS clock <= 400 MHz with fps >= {0} x {1} = {2} (target {0} fps).' -f $TargetFps, $Safety, $need))
[void]$sb.AppendLine(('Task: `detect` = axis-aligned boxes, `obb` = oriented boxes (name heuristic). {0} models listed, {1} pass the rule.' -f $items.Count, $ok))
[void]$sb.AppendLine('Licenses and NMS-free flags: see `detector-catalog.md`. For other targets run `scripts/freq_query.ps1`.')
[void]$sb.AppendLine('')
foreach ($f in $families) {
    $sel = @($items | Where-Object { $_.family -eq $f } | Sort-Object @{ Expression = { $h = ($_.input -split 'x')[0]; if ($h -match '^\d+$') { [int]$h } else { 0 } } }, model)
    if ($sel.Count -eq 0) { continue }
    [void]$sb.AppendLine("## $f")
    [void]$sb.AppendLine('')
    [void]$sb.AppendLine(('| model | task | input | 300 MHz | 400 MHz | rule @ {0} fps |' -f $TargetFps))
    [void]$sb.AppendLine('|---|---|---|---|---|---|')
    foreach ($i in $sel) {
        [void]$sb.AppendLine(('| {0} | {1} | {2} | {3} | {4} | {5} |' -f $i.model, $i.task, $i.input, $i.c300, $i.c400, $i.rule))
    }
    [void]$sb.AppendLine('')
}
$text = $sb.ToString() -replace "`r`n", "`n"
[IO.File]::WriteAllText((Resolve-Path (Split-Path -Parent $Out)).Path + '\' + (Split-Path -Leaf $Out), $text, (New-Object Text.UTF8Encoding($false)))
Write-Output ("Wrote {0} ({1} models, {2} pass the rule at {3} fps)." -f $Out, $items.Count, $ok, $TargetFps)
